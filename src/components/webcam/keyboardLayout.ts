export const MODEL_KEYS = KEY_BOUNDS.map(([code, left, right, back, front], index) => ({ code, index, left, right, back, front }));
export const KEY_CODE_TO_INDEX = new Map(MODEL_KEYS.map(key => [key.code, key.index]));
KEY_CODE_TO_INDEX.set("NumpadEnter", KEY_CODE_TO_INDEX.get("Enter")!);
KEY_CODE_TO_INDEX.set("ControlRight", KEY_CODE_TO_INDEX.get("ControlLeft")!);

export function modelKeyAt(x: number, y: number) {
  // 0.003 model units covers four-decimal measurement rounding, not gaps.
  return MODEL_KEYS.find(key => x >= key.left - 0.003 && x <= key.right + 0.003 && y >= key.back - 0.003 && y <= key.front + 0.003)?.index ?? -1;
}
